"""
Equilibrium interlayer separation vs in-plane strain (AB and AA stacking).

Equilibrium in-plane lattice constant reference: ``LAT_CON = 2.4694`` Å (see
:mod:`blg_model_builder.strain_data`).

DFT reference: single-point energies in ``data/blg_poisson_ratio_structures.xyz``
(generated by ``DD-TETB/generate_data/gen_training_data_structures.py``).  At each
stacking and uniaxial strain along lattice vector 1 (``dy = 0``), a quadratic
``E(d)`` is fit to the five sampled interlayer separations; the vertex gives
``d_eq(ε)``.

Model ensemble: total energies on the same structures for each MCMC draw;
``d_eq(ε)`` is extracted the same way.  Plots show ensemble mean ± std with DFT
overlay.  At the end, prints the out-of-plane Poisson ratio
``ν = −d(d_eq)/dε|_{ε=0}`` for DFT and ensemble (mean ± std).

Output:

* ``figures/<model>_<stacking>_poisson_layer_sep.png`` — equilibrium separation vs strain
* ``figures/<model>_<stacking>_poisson_ratio_histogram.png`` — ensemble ν histogram with DFT line
* ``figures/DFT_<stacking>_poisson_energy_vs_sep.png`` — DFT energy vs separation PES

Examples
--------
::

    python visualizations/plot_poisson_ratio.py --models POD_energy
    python visualizations/plot_poisson_ratio.py \\
        --models 'POD_energy_POD_index*' --n-samples 50 --temperature 0.5

With no ``--models``, uses the ``POD_energy_POD_index*`` ensemble with the lowest
NLL on the saved calibration grid (temperature at minimum miscalibration area).
"""

